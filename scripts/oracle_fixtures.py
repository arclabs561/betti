"""Regenerate the external-oracle fixtures in tests/fixtures/oracle/.

Each case is a small fixed point cloud. GUDHI computes the Vietoris-Rips
persistence diagram (full 2-skeleton, Euclidean distances, coefficients in
GF(2)) for dimensions 0 and 1, and Ripser computes the same diagram as an
independent cross-check. The script refuses to write anything if the two
disagree by more than RIPSER_TOLERANCE; Ripser stores distances as float32,
so its values are only good to about 1e-7 relative, and GUDHI's double
precision values are the ones written out.

Both tools omit zero-persistence pairs, so the fixtures do too.

Usage, from any directory (the output path is explicit so the tools never run
inside the repository):

    uv run --no-project scripts/oracle_fixtures.py tests/fixtures/oracle
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import gudhi
import numpy as np
import ripser

RIPSER_TOLERANCE = 1e-5
DIMENSIONS = (0, 1)


def square() -> np.ndarray:
    # Hand-checkable: four components merge at 1, one loop lives on [1, sqrt 2).
    return np.array([[0.0, 0.0], [1.0, 0.0], [1.0, 1.0], [0.0, 1.0]])


def noisy_circle() -> np.ndarray:
    rng = np.random.default_rng(7)
    angles = np.sort(rng.uniform(0.0, 2.0 * math.pi, 16))
    radii = 1.0 + rng.normal(0.0, 0.05, 16)
    return np.column_stack([radii * np.cos(angles), radii * np.sin(angles)])


def uniform_plane() -> np.ndarray:
    return np.random.default_rng(11).uniform(0.0, 1.0, (20, 2))


def uniform_cube() -> np.ndarray:
    return np.random.default_rng(13).uniform(0.0, 1.0, (15, 3))


def two_blobs() -> np.ndarray:
    rng = np.random.default_rng(17)
    left = rng.normal(0.0, 0.1, (10, 2))
    right = rng.normal(0.0, 0.1, (10, 2)) + np.array([3.0, 0.0])
    return np.vstack([left, right])


CASES = {
    "square": square,
    "noisy_circle": noisy_circle,
    "uniform_plane": uniform_plane,
    "uniform_cube": uniform_cube,
    "two_blobs": two_blobs,
}


def gudhi_diagram(points: np.ndarray) -> dict[int, list[tuple[float, float]]]:
    tree = gudhi.RipsComplex(points=points).create_simplex_tree(max_dimension=2)
    tree.compute_persistence(homology_coeff_field=2, min_persistence=0.0)
    return {
        dim: sorted(
            (float(birth), float(death))
            for birth, death in tree.persistence_intervals_in_dimension(dim)
        )
        for dim in DIMENSIONS
    }


def ripser_diagram(points: np.ndarray) -> dict[int, list[tuple[float, float]]]:
    diagrams = ripser.ripser(points, maxdim=max(DIMENSIONS), coeff=2)["dgms"]
    return {
        dim: sorted((float(birth), float(death)) for birth, death in diagrams[dim])
        for dim in DIMENSIONS
    }


def close(left: float, right: float) -> bool:
    if math.isinf(left) or math.isinf(right):
        return left == right
    return abs(left - right) <= RIPSER_TOLERANCE


def check_agreement(name: str, primary, secondary) -> None:
    for dim in DIMENSIONS:
        ours, theirs = primary[dim], secondary[dim]
        if len(ours) != len(theirs) or not all(
            close(a, c) and close(b, d) for (a, b), (c, d) in zip(ours, theirs)
        ):
            raise SystemExit(
                f"{name}: GUDHI and Ripser disagree in H{dim}\n"
                f"  gudhi:  {ours}\n  ripser: {theirs}"
            )


def write_case(directory: Path, name: str, points: np.ndarray, diagram) -> None:
    header = (
        f"# {name}: generated by scripts/oracle_fixtures.py with "
        f"gudhi {gudhi.__version__}, cross-checked against ripser {ripser.__version__}\n"
    )
    lines = [header, "# one point per line\n"]
    lines += [" ".join(repr(float(x)) for x in point) + "\n" for point in points]
    (directory / f"{name}.points").write_text("".join(lines))

    lines = [header, "# dimension birth death; death inf is an essential class\n"]
    for dim in DIMENSIONS:
        for birth, death in diagram[dim]:
            lines.append(f"{dim} {birth!r} {'inf' if math.isinf(death) else repr(death)}\n")
    (directory / f"{name}.diagram").write_text("".join(lines))


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    directory = Path(sys.argv[1])
    directory.mkdir(parents=True, exist_ok=True)
    for name, make in CASES.items():
        # Six decimals keep the files readable; the rounded values are the
        # inputs both here and in the Rust test, so nothing is lost.
        points = np.round(make(), 6)
        primary = gudhi_diagram(points)
        check_agreement(name, primary, ripser_diagram(points))
        write_case(directory, name, points, primary)
        counts = ", ".join(f"H{dim}: {len(primary[dim])}" for dim in DIMENSIONS)
        print(f"{name}: {len(points)} points, {counts}")


if __name__ == "__main__":
    main()
